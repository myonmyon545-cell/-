import fs from 'node:fs/promises';
import {FileBlob, SpreadsheetFile} from '@oai/artifact-tool';

const [input, out] = process.argv.slice(2);
await fs.mkdir(out, {recursive:true});
const start=Date.now();
console.log('import:start');
const wb = await SpreadsheetFile.importXlsx(await FileBlob.load(input));
console.log('import:done',Date.now()-start);
console.log((await wb.inspect({kind:'sheet',include:'id,name',maxChars:3000})).ndjson);
const preview=await wb.render({sheetName:'Ⅰ基礎情報',range:'B249:R270',scale:1.5,format:'png'});
await fs.writeFile(out+'/before.png',new Uint8Array(await preview.arrayBuffer()));
await fs.writeFile(out+'/pilot_import.json',JSON.stringify({originalF260:wb.worksheets.getItem('Ⅰ基礎情報').getRange('F260:F261').values}));
console.log('before_render:done');
const ws=wb.worksheets.add('分析要点');
ws.showGridLines=false;
ws.getRange('A2:D2').merge();
ws.getRange('A2').values=[['出力保持試行 — 最終成果ではありません']];
ws.getRange('A4:D8').values=[['項目','分子','分母','割合'],['第1号被保険者認定率',5125,32297,null],['三島市／2025年1月基準',null,null,null],['C03：一次判定件数の照合待ち',null,null,null],['C04：調査期間の確認待ち',null,null,null]];
ws.getRange('D5').formulas=[['=B5/C5']];
ws.getRange('A2:D8').format.font={name:'Arial',size:11};
ws.getRange('A2').format.font={name:'Arial',size:15,bold:true};
ws.getRange('A4:D4').format={fill:'#26445C',font:{name:'Arial',size:11,bold:true,color:'#FFFFFF'}};
ws.getRange('A:A').format.columnWidth=46;
ws.getRange('B:D').format.columnWidth=15;
ws.getRange('A2:D8').format.rowHeight=26;
ws.getRange('D5').setNumberFormat('0.0%');
wb.recalculate();
const expected=5125/32297;
const got=ws.getRange('D5').values[0][0];
if(Math.abs(got-expected)>1e-10)throw Error('pilot ratio did not recalculate');
ws.getRange('B5').values=[[6000]];
wb.recalculate();
if(Math.abs(ws.getRange('D5').values[0][0]-6000/32297)>1e-10)throw Error('changed input failed');
ws.getRange('B5').values=[[5125]];
wb.recalculate();
const after=await wb.render({sheetName:'分析要点',range:'A1:D9',scale:1.5,format:'png'});
await fs.writeFile(out+'/summary.png',new Uint8Array(await after.arrayBuffer()));
console.log((await wb.inspect({kind:'table',range:'分析要点!A4:D8',include:'values,formulas',tableMaxRows:5,tableMaxCols:4})).ndjson);
console.log('export:start');
await(await SpreadsheetFile.exportXlsx(wb)).save(out+'/pilot.xlsx');
await fs.writeFile(out+'/pilot_runtime.json',JSON.stringify({expected,got,changedInputRecalculated:true,elapsedSeconds:(Date.now()-start)/1000}));
console.log('export:done',Date.now()-start);
